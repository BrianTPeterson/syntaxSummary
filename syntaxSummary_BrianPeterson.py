
# Number: An integer representing the number of counties
counties = 64
print(counties)

# String: A city name stored as text
city = "Denver"
print(city)

# List: A collection of city names that can be modified
cities = ["Denver", "Pueblo", "Boulder"]
print(cities)

# Tuple: Geographic coordinates that cannot be modified
coordinates = (39.7392, -104.9903)
print(coordinates)

# Dictionary: Geographic information stored as key-value pairs
location = {"city": "Denver", "state": "Colorado"}
print(location)
